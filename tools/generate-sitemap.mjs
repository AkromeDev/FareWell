#!/usr/bin/env node
/**
 * Writes dist/farewell/browser/sitemap.xml from the prerendered pages.
 * Runs in `npm run prerender` after tools/flatten-prerender.mjs.
 *
 * A page is listed when its HTML says it may be indexed (robots without
 * "noindex") and its canonical points at itself. That keeps out, without a
 * list to maintain: the /uk pages (noindex until reviewed), the 404 and
 * not-found page, the internal pages, the redirect stubs and the A/B variants
 * of /promotionen (canonical to /promotionen). A new page is listed as soon
 * as it is prerendered with index,follow.
 *
 * tools/sitemap-meta.json adds <lastmod> and <priority> per address. lastmod
 * is the date of the last real change of a page's content, not the deploy
 * date: update it there when a page's text changes. EXCLUDED holds the few
 * indexable pages that are kept out of the sitemap on purpose.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ORIGIN = 'https://farewell.salon';
const root = join(import.meta.dirname, '..', 'dist', 'farewell', 'browser');
const meta = JSON.parse(readFileSync(join(import.meta.dirname, 'sitemap-meta.json'), 'utf8'));

/** Indexable, but deliberately not offered to search engines. */
const EXCLUDED = new Set([
  // Onboarding guide for massage therapists who already work with us.
  '/karriere/masseur-nuernberg/onboarding',
  '/en/karriere/masseur-nuernberg/onboarding',
]);

if (!existsSync(join(root, 'index.html'))) {
  console.error(`generate-sitemap: no prerender output at ${root}`);
  process.exit(1);
}

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.html')) out.push(p);
  }
  return out;
}

const urls = [];
for (const file of walk(root)) {
  const html = readFileSync(file, 'utf8');
  const robots = /<meta name="robots" content="([^"]*)"/.exec(html)?.[1] ?? '';
  if (robots.includes('noindex')) continue;
  const canonical = /<link rel="canonical" href="([^"]*)"/.exec(html)?.[1];
  const rel = relative(root, file).replace(/\.html$/, '');
  const path = rel === 'index' ? '/' : `/${rel}`;
  if (canonical !== `${ORIGIN}${path}`) continue;
  if (EXCLUDED.has(path)) continue;
  urls.push(path);
}

// German pages first, then English, each in path order; the home page on top.
const rank = (p) => (p === '/' ? 0 : p === '/en' ? 2 : p.startsWith('/en/') ? 3 : 1);
urls.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

const entry = (path) => {
  const m = meta[path] ?? {};
  return [
    '  <url>',
    `    <loc>${ORIGIN}${path}</loc>`,
    ...(m.lastmod ? [`    <lastmod>${m.lastmod}</lastmod>`] : []),
    ...(m.priority ? [`    <priority>${m.priority}</priority>`] : []),
    '  </url>',
  ].join('\n');
};

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/generate-sitemap.mjs at build time. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(entry).join('\n')}
</urlset>
`;
writeFileSync(join(root, 'sitemap.xml'), xml);
console.log(`generate-sitemap: ${urls.length} addresses in sitemap.xml`);
